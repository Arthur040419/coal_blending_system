CREATE TABLE IF NOT EXISTS `experiment_record` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `experiment_code` varchar(50) DEFAULT NULL COMMENT '实验编号，同一次生成请求使用同一编号',
  `order_id` bigint DEFAULT NULL COMMENT '订单ID',
  `model_name` varchar(50) DEFAULT NULL COMMENT '模型名称：优化前/优化后模型或系统枚举',
  `plan_id` bigint DEFAULT NULL COMMENT '生成的方案ID',
  `total_cost` decimal(12,2) DEFAULT NULL COMMENT '总成本',
  `avg_ash` decimal(6,2) DEFAULT NULL COMMENT '预测灰分',
  `avg_sulfur` decimal(6,3) DEFAULT NULL COMMENT '预测硫分',
  `avg_moisture` decimal(6,2) DEFAULT NULL COMMENT '预测水分',
  `avg_calorific` decimal(8,2) DEFAULT NULL COMMENT '预测发热量',
  `quality_score` decimal(6,2) DEFAULT NULL COMMENT '质量匹配评分',
  `cost_score` decimal(6,2) DEFAULT NULL COMMENT '成本评分',
  `inventory_score` decimal(6,2) DEFAULT NULL COMMENT '库存合理性评分',
  `final_score` decimal(6,2) DEFAULT NULL COMMENT '综合评分',
  `ai_candidate_plan_count` int DEFAULT NULL COMMENT '大模型返回候选方案数',
  `accepted_ai_candidate_count` int DEFAULT NULL COMMENT '通过基础校验并进入评分的AI候选数',
  `total_candidate_count` int DEFAULT NULL COMMENT '本次参与决策候选总数',
  `feasible_candidate_count` int DEFAULT NULL COMMENT '可执行候选数',
  `risky_candidate_count` int DEFAULT NULL COMMENT '风险参考候选数',
  `infeasible_candidate_count` int DEFAULT NULL COMMENT '不可执行候选数',
  `generated_plan_count` int DEFAULT NULL COMMENT '本次落库展示方案数',
  `llm_success_flag` tinyint DEFAULT NULL COMMENT '大模型是否返回可解析候选：1是0否',
  `ai_candidate_error` text COMMENT 'AI候选生成错误',
  `effective_candidate_rate` decimal(8,4) DEFAULT NULL COMMENT '有效候选率',
  `model_effect_score` decimal(8,2) DEFAULT NULL COMMENT '模型综合效果分',
  `constraint_hit` text COMMENT '命中的约束、风险和评分说明JSON',
  `risk_warning` text COMMENT '风险提示',
  `explain_text` text COMMENT '模型生成理由和评分解释',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_experiment_order` (`order_id`),
  KEY `idx_experiment_code` (`experiment_code`),
  KEY `idx_experiment_model` (`model_name`),
  KEY `idx_experiment_plan` (`plan_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='模型配煤方案质量评估实验记录';
